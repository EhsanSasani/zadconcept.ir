def guide_for_category(category):
    if category.section != Category.Section.FLOWERS:
        return None
    guide = COLLECTION_GUIDES.get(category.slug)
    if not guide:
        return None
    return {
        **guide,
        "links": [
            {"label": "گل‌های آماده برای امروز", "url": reverse("flowers_same_day")},
            {"label": "راهنمای سفارش گل در مشهد", "url": reverse("mashhad_flower_order")},
            {"label": "شرایط و محدودهٔ ارسال", "url": reverse("delivery_policy")},
        ],
    }
